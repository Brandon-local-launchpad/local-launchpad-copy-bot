define( 'LLP_COPYBOT_VERSION', '0.1.0' );
define( 'LLP_COPYBOT_OPTION', 'llp_client_values' );

// ── Client Values ────────────────────────────────────────────────────────────

/** The keys the settings page shows: [ { key, label }, … ] (generated by Copybot). */
function llp_copybot_keys() {
	static $keys = null;
	if ( null === $keys ) {
		$raw  = file_get_contents( __DIR__ . '/client-value-keys.json' );
		$keys = $raw ? json_decode( $raw, true ) : array();
		$keys = is_array( $keys ) ? $keys : array();
	}
	return $keys;
}

/** All stored values: [ key => value ]. */
function llp_copybot_values() {
	$values = get_option( LLP_COPYBOT_OPTION, array() );
	return is_array( $values ) ? $values : array();
}

/**
 * One client value. years_trading, when not stored, is worked out from a
 * 4-digit year_founded so it stays right each year.
 */
function llp_cv( $key ) {
	$values = llp_copybot_values();
	$value  = isset( $values[ $key ] ) ? (string) $values[ $key ] : '';
	if ( '' === $value && 'years_trading' === $key && isset( $values['year_founded'] ) && preg_match( '/^\d{4}$/', (string) $values['year_founded'] ) ) {
		$value = (string) ( (int) current_time( 'Y' ) - (int) $values['year_founded'] );
	}
	return $value;
}

/**
 * Replace [CV: key] tokens. A key with no value becomes '' (never a visible token).
 * $mode 'html': values are HTML-escaped (WYSIWYG fields, SEO meta).
 * $mode 'text': tags are stripped (plain fields; the theme escapes them).
 */
function llp_copybot_resolve( $text, $mode = 'text' ) {
	if ( ! is_string( $text ) || false === strpos( $text, '[CV: ' ) ) {
		return $text;
	}
	return preg_replace_callback(
		'/\[CV: ([a-z0-9_]+)\]/',
		function ( $m ) use ( $mode ) {
			$value = llp_cv( $m[1] );
			return 'html' === $mode ? esc_html( $value ) : wp_strip_all_tags( $value );
		},
		$text
	);
}

/** Sanitise a full set of values. Keys not on the list are dropped. */
function llp_copybot_sanitize( $input ) {
	if ( ! is_array( $input ) ) {
		return llp_copybot_values();
	}
	$out = array();
	foreach ( llp_copybot_keys() as $k ) {
		$key = $k['key'];
		if ( ! array_key_exists( $key, $input ) ) {
			continue;
		}
		$value       = is_scalar( $input[ $key ] ) ? (string) $input[ $key ] : '';
		$out[ $key ] = in_array( $key, array( 'map_embed', 'review_url', 'price_list' ), true )
			? esc_url_raw( trim( $value ) )
			: sanitize_textarea_field( $value );
	}
	return $out;
}

// Replace tokens when a page is shown, not in the editor or the REST API (Copybot
// reads the raw tokens back to compare).
function llp_copybot_should_resolve() {
	if ( defined( 'REST_REQUEST' ) && REST_REQUEST ) {
		return false;
	}
	return ! ( is_admin() && ! wp_doing_ajax() );
}

add_filter(
	'acf/format_value',
	function ( $value, $post_id, $field ) {
		if ( ! is_string( $value ) || ! llp_copybot_should_resolve() ) {
			return $value;
		}
		return llp_copybot_resolve( $value, 'wysiwyg' === $field['type'] ? 'html' : 'text' );
	},
	20,
	3
);

// SEO title and description (Rank Math, Yoast)
foreach ( array( 'rank_math/frontend/title', 'rank_math/frontend/description', 'wpseo_title', 'wpseo_metadesc', 'wpseo_opengraph_title', 'wpseo_opengraph_desc' ) as $llp_hook ) {
	add_filter(
		$llp_hook,
		function ( $text ) {
			return llp_copybot_resolve( $text, 'text' );
		},
		20
	);
}

// [llp_cv key="phone"] for the template (buttons, rating line, footer, map)
add_shortcode(
	'llp_cv',
	function ( $atts ) {
		$atts = shortcode_atts( array( 'key' => '' ), $atts );
		return esc_html( llp_cv( sanitize_key( $atts['key'] ) ) );
	}
);

// ── Settings → Client Values ─────────────────────────────────────────────────

add_action(
	'admin_init',
	function () {
		register_setting(
			'llp_copybot',
			LLP_COPYBOT_OPTION,
			array(
				'type'              => 'array',
				'sanitize_callback' => 'llp_copybot_sanitize',
				'default'           => array(),
			)
		);
	}
);

add_action(
	'admin_menu',
	function () {
		add_options_page( 'Client Values', 'Client Values', 'manage_options', 'llp-client-values', 'llp_copybot_settings_page' );
	}
);

function llp_copybot_settings_page() {
	if ( ! current_user_can( 'manage_options' ) ) {
		return;
	}
	$values = llp_copybot_values();
	echo '<div class="wrap"><h1>Client Values</h1>';
	echo '<p>These replace the <code>[CV: key]</code> tokens in the page copy, and fill <code>[llp_cv key="…"]</code> shortcodes in the template. Copybot pushes them; a change made here is overwritten by its next push.</p>';
	echo '<form method="post" action="options.php">';
	settings_fields( 'llp_copybot' );
	echo '<table class="form-table" role="presentation">';
	foreach ( llp_copybot_keys() as $k ) {
		$key   = $k['key'];
		$value = isset( $values[ $key ] ) ? $values[ $key ] : '';
		printf(
			'<tr><th scope="row"><label for="llp_cv_%1$s">%2$s</label></th><td><input type="text" class="regular-text" id="llp_cv_%1$s" name="%3$s[%1$s]" value="%4$s"> <code>[CV: %1$s]</code></td></tr>',
			esc_attr( $key ),
			esc_html( $k['label'] ),
			esc_attr( LLP_COPYBOT_OPTION ),
			esc_attr( $value )
		);
	}
	echo '</table>';
	submit_button();
	echo '</form></div>';
}

// ── ACF field groups (master copy) and REST access ───────────────────────────

add_filter(
	'acf/settings/load_json',
	function ( $paths ) {
		$paths[] = __DIR__ . '/acf-json';
		return $paths;
	}
);

// Let Copybot write the SEO title and description through /wp/v2/pages
add_action(
	'init',
	function () {
		foreach ( array( 'rank_math_title', 'rank_math_description', '_yoast_wpseo_title', '_yoast_wpseo_metadesc' ) as $key ) {
			register_post_meta(
				'page',
				$key,
				array(
					'type'              => 'string',
					'single'            => true,
					'show_in_rest'      => true,
					'sanitize_callback' => 'sanitize_text_field',
					'auth_callback'     => function () {
						return current_user_can( 'edit_pages' );
					},
				)
			);
		}
	}
);

add_action(
	'rest_api_init',
	function () {
		$admin = function () {
			return current_user_can( 'manage_options' );
		};
		register_rest_route(
			'llp-copybot/v1',
			'/client-values',
			array(
				array(
					'methods'             => 'GET',
					'callback'            => function () {
						return rest_ensure_response( (object) llp_copybot_values() );
					},
					'permission_callback' => $admin,
				),
				array(
					'methods'             => 'POST',
					'callback'            => function ( WP_REST_Request $request ) {
						$input = $request->get_json_params();
						if ( ! is_array( $input ) ) {
							return new WP_Error( 'llp_bad_body', 'Send a JSON object of key: value.', array( 'status' => 400 ) );
						}
						$clean = llp_copybot_sanitize( array_merge( llp_copybot_values(), $input ) );
						update_option( LLP_COPYBOT_OPTION, $clean );
						return rest_ensure_response( (object) $clean );
					},
					'permission_callback' => $admin,
				),
			)
		);
		register_rest_route(
			'llp-copybot/v1',
			'/status',
			array(
				'methods'             => 'GET',
				'callback'            => function () {
					$groups = function_exists( 'acf_get_field_groups' )
						? array_values( array_filter( wp_list_pluck( acf_get_field_groups(), 'key' ), function ( $k ) {
							return 0 === strpos( $k, 'group_llp_' );
						} ) )
						: array();
					return rest_ensure_response(
						array(
							'plugin'       => LLP_COPYBOT_VERSION,
							'acf_pro'      => defined( 'ACF_PRO' ) && ACF_PRO,
							'seo'          => defined( 'RANK_MATH_VERSION' ) ? 'rankmath' : ( defined( 'WPSEO_VERSION' ) ? 'yoast' : 'none' ),
							'front_page'   => (int) get_option( 'page_on_front' ),
							'field_groups' => $groups,
						)
					);
				},
				'permission_callback' => function () {
					return current_user_can( 'edit_pages' );
				},
			)
		);
	}
);

add_action(
	'admin_notices',
	function () {
		if ( current_user_can( 'activate_plugins' ) && ! ( defined( 'ACF_PRO' ) && ACF_PRO ) ) {
			echo '<div class="notice notice-error"><p><strong>Local Launchpad Copybot</strong> needs ACF Pro for the homepage fields.</p></div>';
		}
	}
);
